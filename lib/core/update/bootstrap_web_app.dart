function nodeOrigin() { return window.location.protocol + '//' + window.location.host; }

async function fetchWithProgress(url, onProgress) {
  var resp = await fetch(url, { cache: 'no-store' });
  if (!resp.ok) {
    var err = new Error('HTTP ' + resp.status);
    err.status = resp.status;
    throw err;
  }
  var lengthHeader = resp.headers.get('Content-Length');
  var total = lengthHeader ? parseInt(lengthHeader, 10) : 0;
  if (!resp.body || !resp.body.getReader) {
    var buf = await resp.arrayBuffer();
    if (onProgress) onProgress(buf.byteLength, buf.byteLength || total);
    return new Uint8Array(buf);
  }
  var reader = resp.body.getReader();
  var chunks = [];
  var received = 0;
  for (;;) {
    var res = await reader.read();
    if (res.done) break;
    chunks.push(res.value);
    received += res.value.length;
    if (onProgress) onProgress(received, total);
  }
  var out = new Uint8Array(received);
  var offset = 0;
  chunks.forEach(function (c) { out.set(c, offset); offset += c.length; });
  return out;
}

// v4_2 §26.6.3: this node may not hold our platform (an Android inviter
// cannot serve a Linux visitor). The 404 above asks it to fetch one; poll its
// progress here. Same-origin, bounded, and only while the user is actively
// installing — it ends with the attempt, it is not background polling.
async function waitForForeignAcquisition(origin, platform) {
  var deadline = Date.now() + 300000; // 5 min ceiling
  var announced = false;
  for (;;) {
    var st;
    try {
      var resp = await fetch(origin + '/cleona/status/' + encodeURIComponent(platform),
                             { cache: 'no-store' });
      if (!resp.ok) return false;
      st = await resp.json();
    } catch (e) {
      return false;
    }
    if (st.state === 'ready') { log('This node finished fetching the ' + platform + ' build.'); return true; }
    if (st.state === 'failed' || st.state === 'idle') {
      if (st.error) log('Node could not fetch a ' + platform + ' build: ' + st.error);
      return false;
    }
    if (!announced) {
      announced = true;
      log('This node does not hold a ' + platform + ' build yet — it is fetching one from the network.');
    }
    setStatus('This node is fetching the ' + platform + ' build for you…');
    if (Date.now() > deadline) { log('Gave up waiting for the node to fetch a ' + platform + ' build.'); return false; }
    await new Promise(function (r) { setTimeout(r, 2000); });
  }
}

async function downloadCompleteBinary(base, platform) {
  var url = base + '/cleona/binary/' + encodeURIComponent(platform);
  log('Trying complete binary: ' + url);
  setStep('fetch', 'active');
  return await fetchWithProgress(url, function (received, total) {
    var frac = total > 0 ? received / total : 0;
    setProgress(frac, formatBytes(received) + (total ? ' / ' + formatBytes(total) : ''));
  });
}

