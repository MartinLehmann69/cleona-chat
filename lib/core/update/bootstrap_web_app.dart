function parseHashParams(hash) {
  hash = hash || '';
  if (hash.charAt(0) === '#') hash = hash.slice(1);
  var out = {};
  hash.split('&').forEach(function (part) {
    if (!part) return;
    var idx = part.indexOf('=');
    if (idx < 0) return;
