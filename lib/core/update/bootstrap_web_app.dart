// The SHA-256 check of one delivered binary (deps.check of the chain):
// null when it matches the hash from the link, else the reason.
async function checkHash(binary, expectedHashHex) {
  setStep('fetch', 'done');
  setStep('verify', 'active');
  setStatus('Verifying download…');
  setProgress(1, 'checking SHA-256…');

  var gotHashHex = await sha256Hex(binary);
  if (gotHashHex.toLowerCase() !== String(expectedHashHex).toLowerCase()) {
    setStep('verify', null);
    return 'Hash mismatch — expected ' + expectedHashHex + ', got ' + gotHashHex;
  }
  log('SHA-256 OK: ' + gotHashHex);
  return null;
}

function offerVerified(binary, platform, version) {
